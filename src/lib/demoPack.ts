import type { ForecastRecord, StudySet } from "../../supabase/functions/_shared/engine.ts";

function recorded(
  id: string,
  questionId: string,
  arm: "no_research" | "research",
  probability: number,
  rationale: string,
  claimIds: string[],
): ForecastRecord {
  return {
    id,
    questionId,
    arm,
    probability,
    origin: "recorded",
    rationale,
    model: null,
    claimIds,
    status: "scored",
    withholdReason: null,
  };
}

